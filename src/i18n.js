export function t(lang, key, vars = {}) {
  const val = translations[lang]?.[key] ?? translations['fr'][key] ?? key;
  if (typeof val !== 'string') return val;
  return val.replace(/\{(\w+)\}/g, (_, k) => vars[k] ?? '');
}

